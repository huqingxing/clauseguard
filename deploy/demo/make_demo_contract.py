"""生成演示用合同（deploy/demo/demo-contract.docx）。

为什么要单独一份演示合同：评测集里的 120 份是「指标用」的合成语料，每份只覆盖部分专家范畴
（没有一份同时命中 6 个专家）。而演示要一眼看到六个 Agent 同时点亮、并且有一条高风险需要
人工审批——这份 14 条的短合同就是为此手写的：每个专家至少 2 条在范畴内，第 5 条是
「违约金不设上限且不予退还」的高风险条款（触发 human_approval 断点）。

为什么用脚本生成而不是提交二进制：docx 是 zip，二进制入库无法 review；脚本可复现、
改条款只改文本数组，CI 也能校验它能被切分器正确解析。

用法（仓库根）：
    python-agent/.venv/Scripts/python.exe deploy/demo/make_demo_contract.py
"""

from __future__ import annotations

from pathlib import Path

from docx import Document

OUTPUT = Path(__file__).resolve().parent / "demo-contract.docx"

TITLE = "技术开发合作协议"
PARTIES = "甲方：云栖科技有限公司　　乙方：蓝湾数据服务有限公司"

# 条款文本：每条含「第N条」编号（切分器按编号判定条款头）。
CLAUSES: list[tuple[str, str]] = [
    ("第一条　主体与资质", "甲方应具备有效的营业执照及本合同项下业务所需的经营资质，并向乙方提供加盖公章的复印件。"),
    ("第二条　付款方式", "乙方完成阶段交付后，甲方应在收到合规发票之日起三十日内支付合同价款的百分之三十。"),
    ("第三条　发票与税率", "乙方应在收款后十个工作日内开具增值税专用发票，发票品名与税率应与本合同约定一致。"),
    ("第四条　交付与验收", "乙方应在本合同生效后六十日内完成交付，甲方应在收到交付物后十个工作日内完成验收并出具验收意见。"),
    ("第五条　违约责任", "任何一方违约的，应向对方支付合同总价百分之二十的违约金；违约金总额不设上限，已支付款项不予退还。"),
    ("第六条　不可抗力", "因不可抗力导致一方不能履行合同的，该方应在事件发生后七日内书面通知对方，并采取合理措施减轻损失。"),
    ("第七条　知识产权归属", "乙方在履约过程中形成的职务成果及改进成果的知识产权归甲方所有，乙方不得就上述成果另行主张权利。"),
    ("第八条　开源合规", "交付物如包含开源代码，乙方应披露所涉开源许可证的类型与版本，并保证其与本合同使用方式兼容。"),
    ("第九条　数据与个人信息", "乙方处理个人信息应遵守数据安全与隐私保护的相关要求，采取加密与脱敏措施防止信息泄露。"),
    ("第十条　数据跨境", "涉及数据跨境的，双方应另行签署数据处理协议，并按适用法律完成安全评估与备案。"),
    ("第十一条　争议解决", "因本合同发生的争议，双方应友好协商；协商不成的，提交上海仲裁委员会按其规则仲裁。"),
    ("第十二条　出口管制", "双方应遵守适用的出口管制与经济制裁规定，不得将本合同项下技术用于受限最终用途。"),
    ("第十三条　保密", "双方应对履约中获知的对方商业信息承担保密义务，保密期限自本合同终止后持续三年。"),
    ("第十四条　合同生效", "本合同自双方法定代表人或授权代表签字并加盖公章之日起生效，一式两份，双方各执一份。"),
]


def build(path: Path = OUTPUT) -> Path:
    document = Document()
    document.add_heading(TITLE, level=1)
    document.add_paragraph(PARTIES)
    for heading, body in CLAUSES:
        document.add_paragraph(heading)
        document.add_paragraph(body)
    document.save(path)
    return path


if __name__ == "__main__":
    saved = build()
    print(f"[demo] 已生成 {saved}（{len(CLAUSES)} 条）")
